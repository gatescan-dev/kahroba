"""Light HDL parsing (module/entity ports) and cocotb testbench templates."""
from __future__ import annotations

import re

_V_MOD = re.compile(r"\bmodule\s+(\w+)\s*(#\s*\((?:[^()]|\([^()]*\))*\))?\s*\((.*?)\)\s*;", re.S)
_V_DIR = re.compile(r"\b(input|output|inout)\b\s*(?:wire|reg|logic|signed|\s)*\s*(\[[^\]]+\])?\s*([\w\s,]+)")
_VH_ENT = re.compile(r"\bentity\s+(\w+)\s+is(.*?)\bend\b", re.S | re.I)
_VH_PORT = re.compile(r"\bport\s*\((.*)\)\s*;", re.S | re.I)


def _strip_comments(text: str, vhdl: bool) -> str:
    if vhdl:
        return re.sub(r"--[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def _width(rng: str | None) -> int:
    if not rng:
        return 1
    m = re.match(r"\[\s*(\d+)\s*:\s*(\d+)\s*\]", rng)
    return abs(int(m.group(1)) - int(m.group(2))) + 1 if m else 0


_V_ITEM = re.compile(r"^(input|output|inout)?\s*(?:(?:wire|reg|logic|var|signed|unsigned|tri)\s+)*(\[[^\]]+\])?\s*([A-Za-z_]\w*)\s*(?:=.*)?$", re.S)


def verilog_modules(text: str) -> list[dict]:
    text = _strip_comments(text, False)
    mods = []
    for m in _V_MOD.finditer(text):
        ports, cur_dir, cur_w = [], None, 1
        depth, item, items = 0, "", []
        for ch in m.group(3):  # split on top-level commas only
            depth += ch in "([{"
            depth -= ch in ")]}"
            if ch == "," and depth == 0:
                items.append(item)
                item = ""
            else:
                item += ch
        items.append(item)
        for it in items:
            it = " ".join(it.split())
            mm = _V_ITEM.match(it)
            if not mm:
                continue
            if mm.group(1):
                cur_dir, cur_w = mm.group(1), _width(mm.group(2))
            elif mm.group(2):
                cur_w = _width(mm.group(2))
            if cur_dir:  # non-ANSI headers (names only) are skipped
                ports.append({"name": mm.group(3), "dir": cur_dir, "width": cur_w})
        mods.append({"name": m.group(1), "ports": ports})
    return mods


def vhdl_entities(text: str) -> list[dict]:
    text = _strip_comments(text, True)
    ents = []
    for e in _VH_ENT.finditer(text):
        ports = []
        pm = _VH_PORT.search(e.group(2) + ";")
        if pm:
            for decl in pm.group(1).split(";"):
                if ":" not in decl:
                    continue
                names, rest = decl.split(":", 1)
                rest = rest.strip().lower()
                d = {"in": "input", "out": "output", "inout": "inout", "buffer": "output"}.get(
                    rest.split()[0] if rest else "", "input")
                w = 1
                r = re.search(r"\(\s*(\d+)\s+(?:downto|to)\s+(\d+)\s*\)", rest)
                if r:
                    w = abs(int(r.group(1)) - int(r.group(2))) + 1
                for n in names.split(","):
                    if n.strip():
                        ports.append({"name": n.strip(), "dir": d, "width": w})
        ents.append({"name": e.group(1), "ports": ports})
    return ents


def units(text: str, vhdl: bool) -> list[dict]:
    return vhdl_entities(text) if vhdl else verilog_modules(text)


def cocotb_template(top: str, ports: list[dict], clk: str = "clk", rst: str = "rst",
                    rst_low: bool = False) -> str:
    names = {p["name"] for p in ports}
    ins = [p for p in ports if p["dir"] == "input" and p["name"] not in (clk, rst)]
    outs = [p for p in ports if p["dir"] == "output"]
    has_clk, has_rst = clk in names, rst in names
    L = [
        f'"""cocotb testbench for `{top}` (generated by Kahroba, edit freely).',
        "",
        "How it works: every function decorated with @cocotb.test() is one test.",
        "`dut` is your top-level design; read and drive its ports as dut.<port>.value.",
        "await Timer(...) or await RisingEdge(dut.clk) lets simulated time pass.",
        '"""',
        "import random",
        "",
        "import cocotb",
        "from cocotb.clock import Clock",
        "from cocotb.triggers import ClockCycles, RisingEdge, Timer",
        "",
        "",
    ]
    if has_rst:
        act, inact = (0, 1) if rst_low else (1, 0)
        L += [
            "async def reset(dut, cycles=3):",
            f'    """Hold {rst} active for a few clock cycles."""',
            f"    dut.{rst}.value = {act}",
            f"    await ClockCycles(dut.{clk}, cycles)" if has_clk else "    await Timer(30, unit='ns')",
            f"    dut.{rst}.value = {inact}",
            f"    await RisingEdge(dut.{clk})" if has_clk else "    await Timer(10, unit='ns')",
            "",
            "",
        ]
    L += ["@cocotb.test()", "async def smoke_test(dut):",
          '    """Start the clock, reset, drive random inputs, log the outputs."""']
    if has_clk:
        L.append(f"    cocotb.start_soon(Clock(dut.{clk}, 10, unit='ns').start())")
    for p in ins:
        L.append(f"    dut.{p['name']}.value = 0")
    if has_rst:
        L.append("    await reset(dut)")
    L += ["    for cycle in range(20):"]
    for p in ins:
        L.append(f"        dut.{p['name']}.value = random.getrandbits(len(dut.{p['name']}))")
    L.append(f"        await RisingEdge(dut.{clk})" if has_clk else "        await Timer(10, unit='ns')")
    if outs:
        fmt = ", ".join(f"{o['name']}={{dut.{o['name']}.value}}" for o in outs[:4])
        L.append(f'        dut._log.info(f"cycle {{cycle}}: {fmt}")')
    L += ["    # TODO: replace the log lines with checks, e.g.",
          "    # assert dut.q.value == expected, f\"got {dut.q.value}\"", ""]
    return "\n".join(L)


def verilog_template(name: str) -> str:
    return f"""// {name}.v
module {name} (
    input  wire       clk,
    input  wire       rst,
    input  wire [7:0] a,
    output reg  [7:0] q
);
    always @(posedge clk) begin
        if (rst) q <= 8'd0;
        else     q <= q + a;
    end
endmodule
"""


def vhdl_template(name: str) -> str:
    return f"""-- {name}.vhd
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity {name} is
  port (
    clk : in  std_logic;
    rst : in  std_logic;
    a   : in  std_logic_vector(7 downto 0);
    q   : out std_logic_vector(7 downto 0)
  );
end entity;

architecture rtl of {name} is
  signal acc : unsigned(7 downto 0) := (others => '0');
begin
  process (clk) begin
    if rising_edge(clk) then
      if rst = '1' then acc <= (others => '0');
      else acc <= acc + unsigned(a);
      end if;
    end if;
  end process;
  q <= std_logic_vector(acc);
end architecture;
"""
